const assert = require('node:assert/strict');
const M = require('./model.js');
const store = M.createStore();
const offer = { title: 'Test relacji', company: 'Firma DEMO', location: 'Zawiercie', direction: M.DIRECTIONS[1], mode: 'Hybrydowa', contract: M.CONTRACTS[0], url: 'https://example.org/role?utm_source=test#opis', description: 'Przykład n8n', deadline: '2026-12-01' };
const created = store.saveOffer(offer), app = store.createApplication(created.id);
assert.equal(store.createApplication(created.id).id, app.id, 'Jedna aplikacja na ofertę');
const before = JSON.stringify(store.state);
assert.throws(() => store.saveOffer({ ...offer, title: 'Inna nazwa', url: 'https://example.org/role/' }), M.ValidationError);
assert.equal(JSON.stringify(store.state), before, 'Duplikat nie zmienia innych rekordów');
assert.throws(() => store.saveOffer({ ...offer, title: 'Niebezpieczny link', url: 'javascript:alert(1)' }), M.ValidationError);
assert.throws(() => store.saveOffer({ ...offer, title: 'Zła data', url: '', deadline: '2026-02-30' }), M.ValidationError);
store.saveOffer({ ...offer, title: 'Zmieniony tytuł', url: 'https://example.org/role' }, created.id);
assert.equal(store.offer(app).title, 'Zmieniony tytuł', 'Aplikacja czyta wspólną ofertę');
assert.throws(() => store.setStatus(app.id, 'Wysłana'), M.ValidationError);
assert.equal(app.status, 'Przygotowanie');
store.setStatus(app.id, 'Wysłana', true);
assert.ok(app.history.some(item => item.text.includes('ręczne potwierdzenie')));
assert.throws(() => store.saveTask({ title: 'Błędna relacja', due: '2026-10-15', applicationId: 'brak' }), M.ValidationError);
const task = store.saveTask({ title: 'Test zadania', due: '2026-10-15', applicationId: app.id });
assert.throws(() => store.remove('tasks', task.id, false));
store.toggleTask(task.id); assert.equal(task.done, true);
store.remove('tasks', task.id, true); assert.ok(!store.state.tasks.includes(task));
assert.equal(M.warsawTime('2026-03-29T02:30'), null, 'Nieistniejąca godzina zmiany czasu');
assert.equal(M.warsawTime('2026-10-25T02:30'), null, 'Dwuznaczna godzina zmiany czasu');
assert.equal(new Date(M.warsawTime('2026-10-14T10:00')).toISOString(), '2026-10-14T08:00:00.000Z');
assert.throws(() => store.saveEvent({ title: 'Zły koniec', start: '2026-10-14T10:00', end: '2026-10-14T09:30', applicationId: app.id }), M.ValidationError);
const first = store.addMaterial({ title: 'Wersje', version: '1', kind: 'CV', description: 'Szkic 1' });
store.pinMaterial(app.id, first.id); store.pinMaterial(app.id, first.id);
store.addMaterial({ title: 'Wersje', version: '2', kind: 'CV', description: 'Szkic 2' });
assert.equal(store.state.links.filter(link => link.applicationId === app.id).length, 1, 'Nowa wersja nie przepisuje istniejącego powiązania');
assert.equal(store.state.links.find(link => link.applicationId === app.id).materialId, first.id);
assert.throws(() => store.addMaterial({ title: 'Wersje', version: '1', kind: 'CV' }), M.ValidationError);
store.addNote({ text: 'Zażółć gęślą jaźń', applicationId: app.id });
assert.ok(store.search('zazolc').some(item => item.kind === 'Notatka'));
assert.equal(store.search('zazolc')[0].key, app.id, 'Wynik notatki wskazuje aplikację');
store.reset(); assert.equal(store.state.offers.length, 3);
console.log('PASS: relacje, atomowa walidacja, duplikaty, potwierdzenia, czas Europe/Warsaw, wersje i wyszukiwanie.');
